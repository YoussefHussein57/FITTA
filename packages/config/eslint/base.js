import js from '@eslint/js';
import globals from 'globals';
import tseslint from 'typescript-eslint';
import prettier from 'eslint-config-prettier';

/**
 * Shared ESLint flat config for the FITTA workspace.
 *
 * Type-aware linting is enabled deliberately. The rules it unlocks are the ones
 * that matter most in a NestJS codebase: `no-floating-promises` catches an
 * un-awaited database write, which is a silent data-loss bug that no amount of
 * review reliably finds.
 *
 * @param {{ tsconfigRootDir: string, ignores?: string[] }} options
 */
export function createBaseConfig({ tsconfigRootDir, ignores = [] }) {
  return tseslint.config(
    {
      ignores: [
        '**/node_modules/**',
        '**/dist/**',
        '**/.next/**',
        '**/coverage/**',
        '**/*.tsbuildinfo',
        // Generated by `next build` and overwritten on every run. Linting it
        // reports style violations nobody can fix.
        '**/next-env.d.ts',
        ...ignores,
      ],
    },

    js.configs.recommended,
    ...tseslint.configs.recommendedTypeChecked,
    ...tseslint.configs.stylisticTypeChecked,

    {
      languageOptions: {
        parserOptions: {
          projectService: true,
          tsconfigRootDir,
        },
      },
      rules: {
        // NFR-13: no `any` in application code.
        '@typescript-eslint/no-explicit-any': 'error',

        // An un-awaited promise in a service method is a lost write.
        '@typescript-eslint/no-floating-promises': 'error',
        '@typescript-eslint/no-misused-promises': 'error',

        // Unused code is either a mistake or dead weight; `_` opts out explicitly.
        '@typescript-eslint/no-unused-vars': [
          'error',
          {
            argsIgnorePattern: '^_',
            varsIgnorePattern: '^_',
            caughtErrorsIgnorePattern: '^_',
          },
        ],

        // `import type` keeps runtime imports honest and avoids accidental cycles.
        '@typescript-eslint/consistent-type-imports': [
          'error',
          { prefer: 'type-imports', fixStyle: 'inline-type-imports' },
        ],

        // SECURITY.md §4: raw SQL must be parameterised. A template literal built
        // with `+` is the shape of an injection; this makes it visible.
        'no-restricted-syntax': [
          'error',
          {
            selector:
              'CallExpression[callee.property.name=/^\\$queryRawUnsafe|\\$executeRawUnsafe$/]',
            message:
              'Unsafe raw SQL is forbidden (SECURITY.md §4). Use the tagged-template $queryRaw / $executeRaw.',
          },
        ],

        eqeqeq: ['error', 'always', { null: 'ignore' }],
        'no-console': ['warn', { allow: ['warn', 'error'] }],
      },
    },

    // Plain JavaScript (flat configs, shared config modules, scripts) is not part
    // of any tsconfig project, so type-aware rules have no type information to
    // work from and would throw rather than lint.
    //
    // Note the explicit `...disableTypeChecked.rules` spread: a bare `rules:`
    // block here would *replace* the disabling rules instead of extending them,
    // which silently re-enables every typed rule.
    {
      files: ['**/*.js', '**/*.mjs', '**/*.cjs'],
      ...tseslint.configs.disableTypeChecked,
      languageOptions: {
        // These files run on Node, not in a browser. Without declaring the
        // globals, `no-undef` flags `process`, `console`, and `URL` as typos.
        globals: { ...globals.node },
        // Explicit, not inherited. The type-aware block above has no `files`
        // restriction, so its `projectService: true` reaches these files too —
        // and a `languageOptions` key here replaces rather than merges with
        // whatever `disableTypeChecked` set. Turning the project service off by
        // name is the only version of this that cannot silently regress.
        parserOptions: {
          projectService: false,
          project: false,
          program: null,
        },
      },
      rules: {
        ...tseslint.configs.disableTypeChecked.rules,
        'no-console': 'off',
      },
    },

    // Prettier last: it only disables formatting rules, so it must win.
    prettier,
  );
}

export default createBaseConfig;
